# Cria uma lista vazia para armazenar os itens de compra.
lista_de_compras = []

# Solicita ao usuário três itens para a lista.
item1 = input("Item 1 da lista: ")
item2 = input("Item 2 da lista: ")
item3 = input("Item 3 da lista: ")

# Adiciona os itens informados à lista.
lista_de_compras.append(item1)
lista_de_compras.append(item2)
lista_de_compras.append(item3)

# Exibe a lista completa de compras.
print(lista_de_compras)